"""New Zealand (Auckland) public holidays used as model features."""
import numpy as np
import pandas as pd

NZ_HOLIDAYS = pd.to_datetime([
    "2024-10-28", "2024-12-25", "2024-12-26", "2025-01-01", "2025-01-02", "2025-01-27",
    "2025-02-06", "2025-04-18", "2025-04-21", "2025-04-25", "2025-06-02", "2025-06-20",
    "2025-10-27", "2025-12-25", "2025-12-26", "2026-01-01", "2026-01-02", "2026-01-26",
    "2026-02-06", "2026-04-03", "2026-04-06", "2026-04-27", "2026-06-01", "2026-07-10",
    "2026-10-26", "2026-12-25", "2026-12-28", "2027-01-01", "2027-01-04", "2027-02-01",
    "2027-02-08", "2027-03-26", "2027-03-29", "2027-04-26", "2027-06-07", "2027-06-25",
])


def holiday_flags(idx: pd.DatetimeIndex) -> np.ndarray:
    return pd.DatetimeIndex(idx).normalize().isin(NZ_HOLIDAYS).astype(float).reshape(-1, 1)
